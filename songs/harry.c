// Hedwig's Theme — BPM 160, 3/4 time
#define BEAT  375000   // one beat = 60/160 sec = 375ms
#define E8    187500   // eighth note
#define Q     375000   // quarter note
#define DQ    562500   // dotted quarter
#define H     750000   // half note
#define DH    1125000  // dotted half (full measure in 3/4)
#define GAP   20000

static void play_hedwigs_theme(void) {
    // Phrase 1: B4. | E5 G5 F#5 | E5-- B5 | A5--- | F#5--- |
    play_tone(note_b4, 89, DQ); rest(GAP);

    play_tone(note_e5, 67, E8); rest(GAP);
    play_tone(note_g5, 56, E8); rest(GAP);
    play_tone(note_fs5, 60, Q); rest(GAP);

    play_tone(note_e5, 67, H); rest(GAP);
    play_tone(note_b5, 45, Q); rest(GAP);

    play_tone(note_a5, 50, DH); rest(GAP);

    play_tone(note_fs5, 60, DH); rest(GAP);

    // Phrase 2: E5 G5 F#5 | Eb5-- F5 | B4--- |
    play_tone(note_e5, 67, E8); rest(GAP);
    play_tone(note_g5, 56, E8); rest(GAP);
    play_tone(note_fs5, 60, Q); rest(GAP);

    play_tone(note_eb5, 71, H); rest(GAP);
    play_tone(note_f5, 63, Q); rest(GAP);

    play_tone(note_b4, 89, DH); rest(GAP * 5);

    // Phrase 3 (repeat phrase 1): B4. | E5 G5 F#5 | E5-- B5 |
    play_tone(note_b4, 89, DQ); rest(GAP);

    play_tone(note_e5, 67, E8); rest(GAP);
    play_tone(note_g5, 56, E8); rest(GAP);
    play_tone(note_fs5, 60, Q); rest(GAP);

    play_tone(note_e5, 67, H); rest(GAP);
    play_tone(note_b5, 45, Q); rest(GAP);

    // Phrase 4 (ascending): D5-- C#5 | B5--- | G5--- |
    // Using Eb5 as closest to D#5/Eb for the resolution
    play_tone(note_e5, 67, DH); rest(GAP);

    play_tone(note_g5, 56, DH); rest(GAP);

    // Phrase 5: F#5 G5 F#5 | Eb5-- E5 | B4--- |
    play_tone(note_fs5, 60, E8); rest(GAP);
    play_tone(note_g5, 56, E8); rest(GAP);
    play_tone(note_fs5, 60, Q); rest(GAP);

    play_tone(note_eb5, 71, H); rest(GAP);
    play_tone(note_e5, 67, Q); rest(GAP);

    play_tone(note_b4, 89, DH); rest(GAP);
}

void notmain(void) {
    trace("=== Hedwig's Theme on GPIO 19 ===\n");
    audio_init();

    trace("playing Hedwig's Theme forever...\n");
    while (1)
        play_hedwigs_theme();
}
